import {test,expect} from './fixtures.ts'

test('visitor plus button supports Chinese names, generated/custom masked tokens, cancellation and persistence',async({page,portal},testInfo)=>{
  const card=page.getByRole('region',{name:'邀请访客聊天'})
  await card.getByRole('button',{name:'添加新访客'}).click()
  await expect(card.getByLabel('访客姓名')).toBeFocused()
  const token=card.getByLabel('访客 Token',{exact:true})
  await expect(token).toHaveAttribute('type','password')
  const original=await token.inputValue();expect(original).toMatch(/^[a-f0-9]{64}$/)
  await card.getByRole('button',{name:'重新生成 Token'}).click();expect(await token.inputValue()).not.toBe(original)
  await card.getByRole('button',{name:'显示 Token'}).click();await expect(token).toHaveAttribute('type','text')
  await card.getByRole('button',{name:'隐藏 Token'}).click();await expect(token).toHaveAttribute('type','password')
  await card.getByLabel('访客姓名').fill('不保存')
  await card.getByRole('button',{name:'取消',exact:true}).click()
  expect((await portal.readRecord(portal.agents[0]!.record.id)).config.peers).toHaveLength(1)
  await card.getByRole('button',{name:'添加新访客'}).click()
  await card.getByLabel('访客姓名').fill('小林')
  await token.fill('custom-visitor-token-for-ui')
  await card.getByRole('button',{name:'保存访客'}).click()
  await expect(card.getByText('已添加「小林」。下次启动 Agent 时生效。')).toBeVisible()
  const record=await portal.readRecord(portal.agents[0]!.record.id)
  expect(record.config.peers[1]).toMatchObject({displayName:'小林',token:'custom-visitor-token-for-ui',trusted:true})
  await page.reload();await expect(card.getByRole('option',{name:'小林'})).toHaveCount(1)
  await page.setViewportSize({width:390,height:844})
  await card.getByRole('button',{name:'添加新访客'}).click()
  await card.getByLabel('访客姓名').fill('下一位访客')
  await card.getByRole('button',{name:'收起邀请访客聊天'}).click()
  await card.getByRole('button',{name:'展开邀请访客聊天'}).click()
  await expect(card.getByLabel('访客姓名')).toHaveValue('下一位访客')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({path:testInfo.outputPath('visitor-add-mobile.png'),fullPage:true})
  // Display names remain human-readable in the full editor; renaming retains private identity.
  await page.getByRole('button',{name:'编辑配置',exact:true}).click()
  await page.getByRole('button',{name:'5. 访客',exact:true}).click()
  const name=page.getByLabel('访客名',{exact:true}).nth(1)
  await expect(name).toHaveValue('小林');await name.fill('小林同学')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await expect(page.getByRole('button',{name:'已保存 ✓',exact:true})).toBeVisible()
  expect((await portal.readRecord(record.id)).config.peers[1]).toMatchObject({name:record.config.peers[1]!.name,displayName:'小林同学'})
})

test('duplicate visitor names/tokens and failed saves preserve the form for correction',async({page,portal})=>{
  const card=page.getByRole('region',{name:'邀请访客聊天'})
  await card.getByRole('button',{name:'添加新访客'}).click()
  await card.getByLabel('访客姓名').fill('alice')
  await card.getByRole('button',{name:'保存访客'}).click()
  await expect(card.getByRole('alert')).toContainText('同名')
  await card.getByLabel('访客姓名').fill('新访客')
  await card.getByLabel('访客 Token',{exact:true}).fill(portal.agents[0]!.record.config.peers[0]!.token)
  await card.getByRole('button',{name:'保存访客'}).click()
  await expect(card.getByRole('alert')).toContainText('已在使用')
  await card.getByRole('button',{name:'重新生成 Token'}).click()
  await page.route('**/visitors',route=>route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'保存失败，请重试'})}))
  await card.getByRole('button',{name:'保存访客'}).click();await expect(card.getByRole('alert')).toContainText('保存失败')
  await expect(card.getByLabel('访客姓名')).toHaveValue('新访客')
  await page.unroute('**/visitors')
  await card.getByRole('button',{name:'保存访客'}).click()
  await expect(card.getByText('已添加「新访客」。下次启动 Agent 时生效。')).toBeVisible()
  expect((await portal.readRecord(portal.agents[0]!.record.id)).config.peers).toHaveLength(2)
})
